//! Deterministic SMT-LIB2 serialization for [`super::ast`].

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use super::ast::{AstError, BoolExpr, BvBinaryOp, BvCmpOp, BvExpr, BvUnaryOp};

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct QfbvQuery {
    pub assertion: BoolExpr,
    pub comments: Vec<String>,
}

impl QfbvQuery {
    pub fn new(assertion: BoolExpr) -> Self {
        Self {
            assertion,
            comments: Vec::new(),
        }
    }

    pub fn with_comment(mut self, comment: impl Into<String>) -> Self {
        self.comments.push(comment.into());
        self
    }

    pub fn to_smt2(&self) -> Result<String, AstError> {
        let mut variables = BTreeMap::new();
        collect_bool_variables(&self.assertion, &mut variables)?;

        let mut out = String::new();
        out.push_str("; generated by classifier; QF_BV inequivalence obligation\n");
        for comment in &self.comments {
            for line in comment.lines() {
                out.push_str("; ");
                out.push_str(line);
                out.push('\n');
            }
        }
        out.push_str("(set-logic QF_BV)\n");
        for (name, width) in variables {
            out.push_str(&format!("(declare-fun {name} () (_ BitVec {width}))\n"));
        }
        out.push_str("(assert ");
        render_bool(&self.assertion, &mut out);
        out.push_str(")\n(check-sat)\n(exit)\n");
        Ok(out)
    }

    pub fn write_smt2(&self, path: impl AsRef<Path>) -> Result<(), std::io::Error> {
        let path = path.as_ref();
        let text = self
            .to_smt2()
            .map_err(|error| std::io::Error::new(std::io::ErrorKind::InvalidInput, error))?;
        fs::write(path, text)
    }
}

fn insert_variable(
    variables: &mut BTreeMap<String, u32>,
    name: &str,
    width: u32,
) -> Result<(), AstError> {
    if let Some(previous) = variables.insert(name.to_owned(), width)
        && previous != width
    {
        return Err(AstError(format!(
            "SMT variable `{name}` used at BV{previous} and BV{width}"
        )));
    }
    Ok(())
}

fn collect_bool_variables(
    expression: &BoolExpr,
    variables: &mut BTreeMap<String, u32>,
) -> Result<(), AstError> {
    match expression {
        BoolExpr::Const(_) => Ok(()),
        BoolExpr::Not(value) => collect_bool_variables(value, variables),
        BoolExpr::And(values) | BoolExpr::Or(values) => {
            for value in values {
                collect_bool_variables(value, variables)?;
            }
            Ok(())
        }
        BoolExpr::Xor(left, right) => {
            collect_bool_variables(left, variables)?;
            collect_bool_variables(right, variables)
        }
        BoolExpr::Compare { left, right, .. } => {
            collect_bv_variables(left, variables)?;
            collect_bv_variables(right, variables)
        }
    }
}

fn collect_bv_variables(
    expression: &BvExpr,
    variables: &mut BTreeMap<String, u32>,
) -> Result<(), AstError> {
    match expression {
        BvExpr::Var { name, width } => insert_variable(variables, name, *width),
        BvExpr::Const { .. } => Ok(()),
        BvExpr::Unary { value, .. }
        | BvExpr::Extract { value, .. }
        | BvExpr::Extend { value, .. } => collect_bv_variables(value, variables),
        BvExpr::Binary { left, right, .. } => {
            collect_bv_variables(left, variables)?;
            collect_bv_variables(right, variables)
        }
        BvExpr::Concat { high, low, .. } => {
            collect_bv_variables(high, variables)?;
            collect_bv_variables(low, variables)
        }
        BvExpr::Ite {
            condition,
            then_value,
            else_value,
            ..
        } => {
            collect_bool_variables(condition, variables)?;
            collect_bv_variables(then_value, variables)?;
            collect_bv_variables(else_value, variables)
        }
    }
}

fn render_bool(expression: &BoolExpr, out: &mut String) {
    match expression {
        BoolExpr::Const(true) => out.push_str("true"),
        BoolExpr::Const(false) => out.push_str("false"),
        BoolExpr::Not(value) => {
            out.push_str("(not ");
            render_bool(value, out);
            out.push(')');
        }
        BoolExpr::And(values) => render_bool_nary("and", values, out),
        BoolExpr::Or(values) => render_bool_nary("or", values, out),
        BoolExpr::Xor(left, right) => {
            out.push_str("(xor ");
            render_bool(left, out);
            out.push(' ');
            render_bool(right, out);
            out.push(')');
        }
        BoolExpr::Compare { op, left, right } => {
            out.push('(');
            out.push_str(match op {
                BvCmpOp::Eq => "=",
                BvCmpOp::Ne => "distinct",
                BvCmpOp::Ult => "bvult",
                BvCmpOp::Ule => "bvule",
                BvCmpOp::Ugt => "bvugt",
                BvCmpOp::Uge => "bvuge",
                BvCmpOp::Slt => "bvslt",
                BvCmpOp::Sle => "bvsle",
                BvCmpOp::Sgt => "bvsgt",
                BvCmpOp::Sge => "bvsge",
            });
            out.push(' ');
            render_bv(left, out);
            out.push(' ');
            render_bv(right, out);
            out.push(')');
        }
    }
}

fn render_bool_nary(operator: &str, values: &[BoolExpr], out: &mut String) {
    out.push('(');
    out.push_str(operator);
    for value in values {
        out.push(' ');
        render_bool(value, out);
    }
    out.push(')');
}

fn render_bv(expression: &BvExpr, out: &mut String) {
    match expression {
        BvExpr::Var { name, .. } => out.push_str(name),
        BvExpr::Const { value, width } => {
            out.push_str(&format!("(_ bv{value} {width})"));
        }
        BvExpr::Unary { op, value } => {
            out.push('(');
            out.push_str(match op {
                BvUnaryOp::Not => "bvnot",
                BvUnaryOp::Neg => "bvneg",
            });
            out.push(' ');
            render_bv(value, out);
            out.push(')');
        }
        BvExpr::Binary {
            op, left, right, ..
        } => {
            out.push('(');
            out.push_str(match op {
                BvBinaryOp::Add => "bvadd",
                BvBinaryOp::Sub => "bvsub",
                BvBinaryOp::Mul => "bvmul",
                BvBinaryOp::And => "bvand",
                BvBinaryOp::Or => "bvor",
                BvBinaryOp::Xor => "bvxor",
                BvBinaryOp::Shl => "bvshl",
                BvBinaryOp::Lshr => "bvlshr",
                BvBinaryOp::Ashr => "bvashr",
            });
            out.push(' ');
            render_bv(left, out);
            out.push(' ');
            render_bv(right, out);
            out.push(')');
        }
        BvExpr::Ite {
            condition,
            then_value,
            else_value,
            ..
        } => {
            out.push_str("(ite ");
            render_bool(condition, out);
            out.push(' ');
            render_bv(then_value, out);
            out.push(' ');
            render_bv(else_value, out);
            out.push(')');
        }
        BvExpr::Extract { value, high, low } => {
            out.push_str(&format!("((_ extract {high} {low}) "));
            render_bv(value, out);
            out.push(')');
        }
        BvExpr::Extend {
            value, by, signed, ..
        } => {
            let operation = if *signed {
                "sign_extend"
            } else {
                "zero_extend"
            };
            out.push_str(&format!("((_ {operation} {by}) "));
            render_bv(value, out);
            out.push(')');
        }
        BvExpr::Concat { high, low, .. } => {
            out.push_str("(concat ");
            render_bv(high, out);
            out.push(' ');
            render_bv(low, out);
            out.push(')');
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::qfbv::ast::{BvCmpOp, BvExpr};

    #[test]
    fn serialization_is_typed_and_deterministic() {
        let z = BvExpr::var("z", 32).unwrap();
        let a = BvExpr::var("a", 32).unwrap();
        let assertion = BoolExpr::and([
            BoolExpr::compare(BvCmpOp::Eq, z, BvExpr::constant(32, 1).unwrap()).unwrap(),
            BoolExpr::compare(BvCmpOp::Eq, a, BvExpr::constant(32, 2).unwrap()).unwrap(),
        ]);
        let text = QfbvQuery::new(assertion).to_smt2().unwrap();
        assert_eq!(
            text,
            "; generated by classifier; QF_BV inequivalence obligation\n\
(set-logic QF_BV)\n\
(declare-fun a () (_ BitVec 32))\n\
(declare-fun z () (_ BitVec 32))\n\
(assert (and (= z (_ bv1 32)) (= a (_ bv2 32))))\n\
(check-sat)\n\
(exit)\n"
        );
    }
}
